"""Write or check THIRD_PARTY_LICENSES.txt, the notices of the crates in the wheel.

The compiled extension links Keleusma and its dependencies, several of which are
licensed under terms such as MIT and BSD-3-Clause that require their notices to
accompany binary copies. This script reproduces the license files each linked crate
ships, verbatim, so the wheel carries them through `license-files` in pyproject.toml.

A crate counts as linked when it is reached from this package through normal
dependency edges without passing through a procedural macro, because a procedural
macro and what only it depends on run at compile time and are not in the binary.
Edges for every target platform are followed, so the file is the same on every host
and covers the platform-specific crates of every wheel. Where a crate offers a choice
of licenses, every text it ships is reproduced, and no choice is made here.

Run `uv run python tools/third_party_licenses.py` after changing Cargo.lock, and
`tests/test_packaging.py` runs it with `--check`. It needs the crates' sources, which
any build downloads.
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import cast

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.txt"
LICENSE_FILE = re.compile(
    r"^(licen[cs]e|copying|copyright|notice|unlicense)([-._].*)?$", re.IGNORECASE
)
HEADER = """\
Third-party notices for the pykeleusma wheel

The compiled extension in this distribution links the Rust crates listed below.
Each license text that a crate ships is reproduced verbatim, once per distinct
text, followed by the crates that ship it. Where a crate offers a choice of
licenses, every text it ships is reproduced. This file is generated by
tools/third_party_licenses.py from Cargo.lock and must not be edited by hand.

pykeleusma itself is licensed under the BSD Zero Clause License in LICENSE.
"""

type Json = dict[str, object]


@dataclass(frozen=True)
class Crate:
    name: str
    version: str
    license: str
    directory: Path

    @property
    def label(self) -> str:
        return f"{self.name} {self.version}"


def _objects(value: object) -> list[Json]:
    return cast(list[Json], value)


def _metadata() -> Json:
    result = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],  # noqa: S607
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return cast(Json, json.loads(result.stdout))


def _is_proc_macro(package: Json) -> bool:
    return any(
        "proc-macro" in cast(list[str], target["kind"])
        for target in _objects(package["targets"])
    )


def linked_crates(metadata: Json) -> list[Crate]:
    """The crates reached through normal edges that do not pass a procedural macro."""
    packages = {cast(str, p["id"]): p for p in _objects(metadata["packages"])}
    resolve = cast(Json, metadata["resolve"])
    nodes = {cast(str, n["id"]): n for n in _objects(resolve["nodes"])}
    root = cast(str, resolve["root"])
    seen: set[str] = set()
    pending = [root]
    # Each node is pushed only while unseen, so the loop ends after visiting each
    # package of the finite resolve graph at most once.
    while pending:
        current = pending.pop()
        if current in seen:
            continue
        seen.add(current)
        for dependency in _objects(nodes[current]["deps"]):
            kinds = _objects(dependency["dep_kinds"])
            target = cast(str, dependency["pkg"])
            normal = any(kind["kind"] is None for kind in kinds)
            if normal and not _is_proc_macro(packages[target]):
                pending.append(target)
    seen.discard(root)
    crates = [
        Crate(
            name=cast(str, packages[i]["name"]),
            version=cast(str, packages[i]["version"]),
            license=cast(str | None, packages[i]["license"]) or "unstated",
            directory=Path(cast(str, packages[i]["manifest_path"])).parent,
        )
        for i in seen
    ]
    return sorted(crates, key=lambda c: (c.name, c.version))


def _license_texts(crate: Crate) -> list[str]:
    files = sorted(
        path
        for path in crate.directory.iterdir()
        if path.is_file() and LICENSE_FILE.match(path.name)
    )
    if not files:
        msg = f"{crate.label} ships no license file in {crate.directory}"
        raise SystemExit(msg)
    texts: list[str] = []
    for path in files:
        raw = path.read_text(encoding="utf-8")
        lines = raw.replace("\r\n", "\n").split("\n")
        texts.append("\n".join(line.rstrip() for line in lines).strip("\n") + "\n")
    return texts


def render(crates: list[Crate]) -> str:
    """The notices file, with each distinct text once and its crates after it."""
    holders: dict[str, list[str]] = {}
    for crate in crates:
        for text in _license_texts(crate):
            holders.setdefault(text, []).append(crate.label)
    rule = "=" * 78
    parts = [HEADER, rule, "Crates and their declared licenses", rule, ""]
    parts.extend(f"{c.label}: {c.license}" for c in crates)
    # Ordered by the first crate that ships each text, then by the text's digest, so
    # the output does not depend on dictionary order or on the host.
    ordered = sorted(
        holders.items(),
        key=lambda item: (item[1][0], hashlib.sha256(item[0].encode()).hexdigest()),
    )
    for text, labels in ordered:
        parts.extend(["", rule, "Shipped by " + ", ".join(labels), rule, "", text])
    return "\n".join(parts).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Write or check " + OUTPUT.name)
    parser.add_argument(
        "--check", action="store_true", help="fail if the file is out of date"
    )
    options = parser.parse_args()
    expected = render(linked_crates(_metadata()))
    if options.check:
        current = OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n")
        if current != expected:
            print(f"{OUTPUT.name} is out of date. Run {Path(__file__).name}.")
            return 1
        print(f"{OUTPUT.name} is current.")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.name}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
